import createClient, { type Middleware } from "openapi-fetch";
import {
	clearSession,
	getAccessToken,
	getSessionEpoch,
	setSession,
} from "#/feature/auth/store";
import { NetworkError } from "./errors";
import type { paths } from "./schema"; // generated by openapi-typescript

/** `include` is required for the httpOnly refresh cookie: the API is a different origin. */
export const apiClient = createClient<paths>({
	baseUrl: import.meta.env.VITE_API_URL,
	credentials: "include",
});

/**
 * Endpoints that carry no access token. `/api/auth/refresh` is the load-bearing
 * entry: excluding it stops its own 401 from triggering another refresh.
 */
const PUBLIC_PATHS = new Set<string>([
	"/api/health",
	"/api/auth/login",
	"/api/auth/register",
	"/api/auth/refresh",
	"/api/auth/github",
]);

const isServer = () => typeof window === "undefined";

export type RefreshOutcome =
	| { status: "refreshed" }
	| { status: "rejected" }
	| { status: "unreachable"; cause: unknown }
	| { status: "failed"; cause: unknown };

let refreshing: Promise<RefreshOutcome> | null = null;

async function requestRefresh(): Promise<RefreshOutcome> {
	const startedIn = getSessionEpoch();
	const result = await apiClient
		.POST("/api/auth/refresh")
		.catch((cause: unknown) => ({ cause }));

	if (getSessionEpoch() !== startedIn) return { status: "rejected" };
	if ("cause" in result) return { status: "unreachable", cause: result.cause };

	const { data, response } = result;

	if (response.status === 401) {
		clearSession();
		return { status: "rejected" };
	}

	if (!response.ok) {
		return {
			status: "failed",
			cause: new Error(`Session refresh answered HTTP ${response.status}`),
		};
	}

	try {
		setSession(data);
	} catch (cause) {
		return { status: "failed", cause };
	}

	return { status: "refreshed" };
}

/**
 * Mints a new access token from the refresh cookie.
 *
 * Concurrent callers share one in-flight promise, so a burst of 401s produces a
 * single refresh request instead of a storm.
 *
 * Never rejects. `"rejected"` means the refresh no longer applies: the server
 * refused the cookie (the session is cleared) or the session changed while it
 * was in flight (left as is). `"unreachable"` and `"failed"` say nothing about
 * the cookie, so they keep it. Always `"rejected"` on the server, where the
 * browser's cookie never reaches us.
 */
export function ensureRefreshed(): Promise<RefreshOutcome> {
	if (isServer()) return Promise.resolve({ status: "rejected" });

	if (refreshing === null) {
		refreshing = requestRefresh().finally(() => {
			refreshing = null;
		});
	}

	return refreshing;
}

/**
 * Pre-send copies of in-flight requests, keyed by the id openapi-fetch assigns
 * to each call. A `Request` body is a stream that can only be read once, so a
 * retry needs a clone taken before the original was sent.
 */
const retryable = new Map<string, Request>();

const authMiddleware: Middleware = {
	onRequest({ request, schemaPath, id }) {
		if (PUBLIC_PATHS.has(schemaPath)) return undefined;

		if (!isServer()) {
			retryable.set(id, request.clone());
		}

		const accessToken = getAccessToken();
		if (accessToken) {
			request.headers.set("Authorization", `Bearer ${accessToken}`);
		}

		return request;
	},

	/**
	 * Turns an expired-token 401 into a refresh plus one silent retry. A refresh
	 * without a verdict fails the whole call with its own error.
	 */
	async onResponse({ response, id }) {
		const original = retryable.get(id);
		retryable.delete(id);

		if (response.status !== 401 || !original) return response;

		const outcome = await ensureRefreshed();
		if (outcome.status === "rejected") return response;
		if (outcome.status !== "refreshed") throw outcome.cause;

		original.headers.set("Authorization", `Bearer ${getAccessToken()}`);

		// Plain fetch, not apiClient — the retry must not re-enter this middleware.
		return fetch(original).catch((cause: unknown) => {
			throw original.signal.aborted ? cause : new NetworkError(cause);
		});
	},

	/**
	 * A thrown fetch never reaches onResponse, so drop the clone here instead.
	 * An abort is the caller's decision, not a lost connection: returning nothing
	 * rethrows it as is.
	 */
	onError({ request, error, id }) {
		retryable.delete(id);
		if (request.signal.aborted) return;
		return new NetworkError(error);
	},
};

apiClient.use(authMiddleware);
